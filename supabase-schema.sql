CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    cor TEXT DEFAULT '#e11d48',
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.bandas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    vertente TEXT NOT NULL,
    cidade TEXT NOT NULL,
    integrantes TEXT,
    biografia TEXT,
    destaque BOOLEAN DEFAULT FALSE,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.locais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    endereco TEXT NOT NULL,
    bairro_cidade TEXT NOT NULL,
    capacidade INTEGER NOT NULL DEFAULT 200,
    estrutura TEXT,
    descricao TEXT,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    categoria_id BIGINT REFERENCES public.categorias(id) ON DELETE SET NULL,
    banda_principal TEXT DEFAULT 'Várias Bandas',
    vertente_rock TEXT DEFAULT 'Rock / Metal',
    classificacao TEXT DEFAULT '16 anos',
    data DATE NOT NULL,
    horario TEXT NOT NULL,
    local TEXT NOT NULL,
    endereco TEXT NOT NULL,
    responsavel TEXT NOT NULL,
    vagas_totais INTEGER NOT NULL DEFAULT 100,
    vagas_restantes INTEGER NOT NULL DEFAULT 100,
    destaque BOOLEAN DEFAULT FALSE,
    descricao TEXT NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.eventos ADD COLUMN IF NOT EXISTS banda_principal TEXT DEFAULT 'Várias Bandas';
ALTER TABLE public.eventos ADD COLUMN IF NOT EXISTS vertente_rock TEXT DEFAULT 'Rock / Metal';
ALTER TABLE public.eventos ADD COLUMN IF NOT EXISTS classificacao TEXT DEFAULT '16 anos';

CREATE TABLE IF NOT EXISTS public.inscricoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT REFERENCES public.eventos(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    setor_ingresso TEXT DEFAULT 'Pista Rock',
    codigo_confirmacao TEXT NOT NULL UNIQUE,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    senha TEXT NOT NULL DEFAULT 'rock2026',
    papel TEXT NOT NULL DEFAULT 'administrador',
    status TEXT NOT NULL DEFAULT 'ativo',
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS senha TEXT NOT NULL DEFAULT 'rock2026';

